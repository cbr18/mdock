const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('mdock.language') || 'ru');

  useEffect(() => {
    localStorage.setItem('mdock.language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => DICTIONARY[language]?.[key] || DICTIONARY.ru[key] || key
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function LanguageSwitcher() {
  const { language, setLanguage } = useLanguage();
  return (
    <button
      type="button"
      className="icon-button language-button"
      onClick={() => setLanguage(language === 'ru' ? 'en' : 'ru')}
      title={language === 'ru' ? 'English' : 'Русский'}
      aria-label={language === 'ru' ? 'English' : 'Русский'}
    >
      <Languages size={18} aria-hidden="true" />
      <span>{language === 'ru' ? 'RU' : 'EN'}</span>
    </button>
  );
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error('useLanguage must be used inside LanguageProvider');
  }
  return value;
}
